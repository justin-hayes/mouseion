// A deck analysed by the NLP service names the deployer-provisioned models'
// terms in its APKG description and TSV header, beside the dictionary notice
// (ADR 0111).
func TestModernLanguageExportCarriesAnalysisModelsNotice(t *testing.T) {
	entries := []RenderInput{{
		Language: "de", CanonicalLemma: "haus", UPOS: "NOUN",
		Sentence: "Das Haus steht heute ganz still am Rand der Stadt.", TargetWord: "Haus",
		DictionaryProviderVersion: "dump=2026-09-14", CandidateSenses: []enrichment.LexicalSense{{EvidenceID: "wiktionary:1", Gloss: "house"}},
	}}
	artifact, err := renderAccepted(t.Context(), "alice", "Buch", entries, nil)
	require.NoError(t, err)
	require.Equal(t, 1, artifact.Count)

	t.Run("APKG description carries the notice", func(t *testing.T) {
		require.Contains(t, collectionColumn(t, artifact.APKG, "decks"), AnalysisModelsNotice)
	})
	t.Run("TSV header comments the notice", func(t *testing.T) {
		require.Contains(t, artifact.TSV, "# "+AnalysisModelsNotice+"\n")
	})
	t.Run("TSV header keeps the dictionary notice", func(t *testing.T) {
		require.Contains(t, artifact.TSV, "# "+dictionary.AttributionNotice+"\n")
	})
}

// An imported Ancient Greek deck keeps its source notice and does not claim
// NLP-service annotations.
func TestAncientGreekExportOmitsAnalysisModelsNotice(t *testing.T) {
	entries := []RenderInput{{
		Language: "grc", CanonicalLemma: "λόγος", UPOS: "NOUN", Headword: "λόγος",
		Sentence: "ἐν ἀρχῇ ἦν ὁ λόγος καὶ ὁ λόγος ἦν πρὸς τὸν θεόν.", TargetWord: "λόγος",
	}}
	artifact, err := renderAccepted(t.Context(), "alice", "Anabasis", entries, nil)
	require.NoError(t, err)
	require.Equal(t, 1, artifact.Count)
	decks := collectionColumn(t, artifact.APKG, "decks")

	t.Run("APKG description keeps the source notice", func(t *testing.T) {
		require.Contains(t, decks, "OGA v0.2.0")
	})
	t.Run("APKG description omits the notice", func(t *testing.T) {
		require.NotContains(t, decks, AnalysisModelsNotice)
	})
	t.Run("TSV header keeps the source notice", func(t *testing.T) {
		require.Contains(t, artifact.TSV, "# "+dictionary.AncientGreekSourceNotice+"\n")
	})
	t.Run("TSV header omits the notice", func(t *testing.T) {
		require.NotContains(t, artifact.TSV, AnalysisModelsNotice)
	})
}

func TestDeckDescriptionNamesAnalysisModelsOnlyForNLPAnalysedDecks(t *testing.T) {
	cases := []struct {
		name    string
		entries []RenderInput
		want    string
	}{
		{"a German deck carries the notice", []RenderInput{{Language: "de"}}, "Generated by Mouseion\n\n" + AnalysisModelsNotice},
		{"an Ancient Greek deck carries only its source notice", []RenderInput{{Language: "grc"}}, "Generated by Mouseion\n\n" + dictionary.AncientGreekSourceNotice},
		{"an empty deck carries no notice", nil, "Generated by Mouseion"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			require.Equal(t, tc.want, deckDescription(tc.entries))
		})
	}
}

// Every line of a multi-notice header stays a comment, so no notice is read
// as a note row.
func TestRenderTSVCommentsEveryNoticeLine(t *testing.T) {
	got, err := RenderTSV([]Note{{Identity: "identity"}}, dictionary.AttributionNotice+"\n\n"+AnalysisModelsNotice)
	require.NoError(t, err)

	t.Run("each notice line is a comment", func(t *testing.T) {
		require.True(t, strings.HasPrefix(got, "# "+dictionary.AttributionNotice+"\n#\n# "+AnalysisModelsNotice+"\n"), got)
	})
	t.Run("only the note is read as a row", func(t *testing.T) {
		r := csv.NewReader(strings.NewReader(got))
		r.Comma = '\t'
		r.Comment = '#'
		rows, err := r.ReadAll()
		require.NoError(t, err)
		require.Len(t, rows, 1)
		require.Equal(t, "identity", rows[0][0])
	})
}
