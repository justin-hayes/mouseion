func TestDeterministicStubScenariosCoverRecoveryBoundaries(t *testing.T) {
	fixture, _ := loadTestFixture(t)
	codec, err := enrichment.NewTranslationCodec(enrichment.LLMConfig{Model: fixture.Model})
	if err != nil {
		t.Fatal(err)
	}
	_, items, err := FrozenRequests(codec, fixture, DefaultRunID, DefaultGeneration)
	if err != nil {
		t.Fatal(err)
	}
	output, err := fixedBatchOutput(codec, fixture, items, DefaultRunID, DefaultGeneration)
	if err != nil {
		t.Fatal(err)
	}

	t.Run("success", func(t *testing.T) {
		outcomes, missing, err := codec.DecodeBatchResultsPartial(DefaultRunID, DefaultGeneration, items, bytes.NewReader(output), nil)
		if err != nil || len(outcomes) != len(items) || len(missing) != 0 {
			t.Fatalf("outcomes=%d missing=%v err=%v", len(outcomes), missing, err)
		}
	})
	t.Run("partial failure", func(t *testing.T) {
		id, _ := enrichment.BatchCustomID(DefaultRunID, items[0].Ordinal, DefaultGeneration)
		errorLine := []byte(`{"custom_id":"` + id + `","error":{"code":"rate_limit_exceeded"}}`)
		partialOutput, outputErr := fixedBatchOutput(codec, fixture, items[1:], DefaultRunID, DefaultGeneration)
		if outputErr != nil {
			t.Fatal(outputErr)
		}
		outcomes, missing, err := codec.DecodeBatchResultsPartial(DefaultRunID, DefaultGeneration, items[1:], bytes.NewReader(partialOutput), bytes.NewReader(append(errorLine, '\n')))
		if err == nil || outcomes != nil {
			t.Fatalf("partial failure was not rejected for mismatched item set: outcomes=%v missing=%v err=%v", outcomes, missing, err)
		}
		outcomes, missing, err = codec.DecodeBatchResultsPartial(DefaultRunID, DefaultGeneration, items, bytes.NewReader(partialOutput), bytes.NewReader(append(errorLine, '\n')))
		if err != nil || len(outcomes) != len(items) || len(missing) != 0 || outcomes[items[0].Ordinal].Successful() {
			t.Fatalf("partial outcomes=%v missing=%v err=%v", outcomes, missing, err)
		}
	})
	t.Run("expiry", func(t *testing.T) {
		id, _ := enrichment.BatchCustomID(DefaultRunID, items[0].Ordinal, DefaultGeneration)
		errorLine := []byte(`{"custom_id":"` + id + `","error":{"code":"batch_expired"}}`)
		outcomes, missing, err := codec.DecodeBatchResultsPartial(DefaultRunID, DefaultGeneration, items, nil, bytes.NewReader(append(errorLine, '\n')))
		if err != nil || len(outcomes) != 1 || len(missing) != len(items)-1 {
			t.Fatalf("expiry outcomes=%v missing=%v err=%v", outcomes, missing, err)
		}
	})
	t.Run("cancellation", func(t *testing.T) {
		if !isTerminalStubStatus(enrichment.BatchStatusCancelled) || isTerminalStubStatus(enrichment.BatchStatusInProgress) {
			t.Fatal("cancellation terminal policy changed")
		}
	})
	t.Run("restart", func(t *testing.T) {
		first, second, err := ReplayFixedResponses(context.Background(), codec, fixture, mustRequests(t), DefaultRunID, DefaultGeneration)
		if err != nil || first.Artifact != second.Artifact || !first.ArtifactStable || !second.ArtifactStable {
			t.Fatalf("restart replay=%+v/%+v err=%v", first, second, err)
		}
	})
	t.Run("ambiguous submission", func(t *testing.T) {
		// No provider identity is proof of creation. The only safe stub result is
		// a manual-recovery decision; automatic resubmission would risk billing
		// the same frozen requests twice.
		if submissionDecision(false, false) != "fail_closed_manual_recovery" || submissionDecision(true, false) != "resume_existing" {
			t.Fatal("ambiguous submission did not fail closed")
		}
	})
}

func mustRequests(t *testing.T) []byte {
	_, requests := loadTestFixture(t)
	return requests
}

func isTerminalStubStatus(status enrichment.BatchStatus) bool {
	return status == enrichment.BatchStatusCompleted || status == enrichment.BatchStatusFailed || status == enrichment.BatchStatusExpired || status == enrichment.BatchStatusCancelled
}

func submissionDecision(remoteFound, creationConfirmed bool) string {
	if remoteFound && !creationConfirmed {
		return "resume_existing"
	}
	if !remoteFound && !creationConfirmed {
		return "fail_closed_manual_recovery"
	}
	return "created"
}
