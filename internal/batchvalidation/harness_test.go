func loadTestFixture(t *testing.T) (Fixture, []byte) {
	t.Helper()
	files := ReadDefaultFiles("testdata")
	fixture, requests, err := LoadFixture(files)
	if err != nil {
		t.Fatal(err)
	}
	return fixture, requests
}

func TestFrozenFixtureReplaysBothTransportsWithStableArtifacts(t *testing.T) {
	fixture, frozenRequests := loadTestFixture(t)
	codec, err := enrichment.NewTranslationCodec(enrichment.LLMConfig{Model: fixture.Model})
	if err != nil {
		t.Fatal(err)
	}
	syncResult, batchResult, err := ReplayFixedResponses(context.Background(), codec, fixture, frozenRequests, DefaultRunID, DefaultGeneration)
	if err != nil {
		t.Fatal(err)
	}
	if syncResult.Artifact != batchResult.Artifact {
		t.Fatalf("fixed-response artifacts differ: sync=%+v batch=%+v", syncResult.Artifact, batchResult.Artifact)
	}
	if syncResult.Metrics.CacheHits != 1 || syncResult.Metrics.CacheMisses != 2 || batchResult.Metrics.ProviderCalls != 1 || syncResult.Completeness.QualityOmitted != 1 {
		t.Fatalf("unexpected replay metrics: sync=%+v batch=%+v", syncResult.Metrics, batchResult.Metrics)
	}
	if !syncResult.ArtifactStable || !batchResult.ArtifactStable || syncResult.Quality.TargetAligned != batchResult.Quality.TargetAligned {
		t.Fatalf("replay is not stable/aligned: sync=%+v batch=%+v", syncResult, batchResult)
	}
}

func TestFrozenRequestFixtureRejectsSemanticDrift(t *testing.T) {
	fixture, frozenRequests := loadTestFixture(t)
	codec, err := enrichment.NewTranslationCodec(enrichment.LLMConfig{Model: fixture.Model})
	if err != nil {
		t.Fatal(err)
	}
	changed := bytes.Replace(frozenRequests, []byte(`"model":"gpt-test"`), []byte(`"model":"different-model"`), 1)
	if _, _, err = ReplayFixedResponses(context.Background(), codec, fixture, changed, DefaultRunID, DefaultGeneration); err == nil || !strings.Contains(err.Error(), "frozen request fixture") {
		t.Fatalf("semantic request drift was accepted: %v", err)
	}
}

func TestFrozenRequestsMatchExactProviderJSONL(t *testing.T) {
	fixture, frozenRequests := loadTestFixture(t)
	codec, err := enrichment.NewTranslationCodec(enrichment.LLMConfig{Model: fixture.Model})
	if err != nil {
		t.Fatal(err)
	}
	requests, items, err := FrozenRequests(codec, fixture, DefaultRunID, DefaultGeneration)
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if _, err = codec.WriteBatchJSONL(&generated, DefaultRunID, DefaultGeneration, items); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generated.Bytes(), frozenRequests) || !bytes.Equal(generated.Bytes(), canonicalRequestFile(requests)) {
		t.Fatalf("frozen request bytes differ from provider JSONL")
	}
	if strings.Contains(generated.String(), `"ordinal"`) {
		t.Fatalf("provider JSONL contains validation-only ordinal: %s", generated.String())
	}
}

func TestFrozenFixtureRejectsModelPromptAndResponseDrift(t *testing.T) {
	fixture, _ := loadTestFixture(t)
	codec, err := enrichment.NewTranslationCodec(enrichment.LLMConfig{Model: fixture.Model})
	if err != nil {
		t.Fatal(err)
	}
	for name, mutate := range map[string]func(*Fixture){
		"model":  func(f *Fixture) { f.Model = "different-model" },
		"prompt": func(f *Fixture) { f.PromptVersion = "different-prompt" },
	} {
		t.Run(name, func(t *testing.T) {
			changed := fixture
			mutate(&changed)
			if _, _, err := FrozenRequests(codec, changed, DefaultRunID, DefaultGeneration); err == nil || !strings.Contains(err.Error(), "codec does not match frozen model or prompt version") {
				t.Fatalf("fixture drift was accepted: %v", err)
			}
		})
	}

	unknown := fixture
	unknown.Responses = append(append([]FixtureResponse(nil), fixture.Responses...), FixtureResponse{Ordinal: 99})
	if err := unknown.ValidateResponses(); err == nil || !strings.Contains(err.Error(), "not an accepted manifest item") {
		t.Fatalf("unknown response ordinal was accepted: %v", err)
	}
	missing := fixture
	missing.Responses = append([]FixtureResponse(nil), fixture.Responses[:len(fixture.Responses)-1]...)
	if err := missing.ValidateResponses(); err == nil || !strings.Contains(err.Error(), "does not match accepted item count") {
		t.Fatalf("missing response ordinal was accepted: %v", err)
	}
}

